const axios = require('axios');
const httpStatus = require('http-status');
const { sendResponse } = require('../../../shared/sendResponse');
const { catchAsync } = require('../../../shared/catchAsync');
const config = require('../../../../config');
const Groq = require('groq-sdk');
const Llama = require('./groq.model');
const UserModel = require('../auth/auth.model');
const {
  getAiResponsesBySession,
  getAiResponsesByUserId,
  deleteOneLlamaAiSession,
  deleteAllAiResponsesService,
  deleteAllAiSessionsService,
} = require('./groq.service');
const { generateSessionId } = require('../../../shared/sessionGenerate');

const groq = new Groq({ apiKey: config.groq_api_key });

exports.GroqAiGetResponse = catchAsync(async (req, res) => {
  const prompt = req.body?.prompt;
  const userId = req.body?.user;
  const sessionId = req.body?.sessionId;

  const currentSessionId = sessionId || generateSessionId(24);

  if (!prompt) {
    return sendResponse(res, {
      statusCode: httpStatus.BAD_REQUEST,
      success: false,
      message: 'Validation Error',
      errorMessages: [{ path: 'prompt', message: 'Prompt is required.' }],
    });
  }

  const user = await UserModel.findById(userId);
  if (!user) {
    return sendResponse(res, {
      statusCode: httpStatus.NOT_FOUND,
      success: false,
      message: 'User not found.',
    });
  }

  let response;
  try {
    response = await groq?.chat?.completions?.create({
      messages: [{ role: 'user', content: prompt }],
      model: 'llama3-8b-8192',
    });
  } catch (error) {
    console.error('Groq SDK Error:', error.message);
    return sendResponse(res, {
      statusCode: httpStatus.INTERNAL_SERVER_ERROR,
      success: false,
      message: 'AI model processing failed.',
    });
  }

  const reply = response?.choices?.[0]?.message?.content || null;

  if (!reply) {
    console.error('Error: No valid reply generated by Groq SDK.');
    return sendResponse(res, {
      statusCode: httpStatus.BAD_REQUEST,
      success: false,
      message: 'Validation Error',
      errorMessages: [
        {
          path: 'message',
          message: 'Reply could not be generated by the AI model.',
        },
      ],
    });
  }

  const responseData = {
    prompt,
    model: response?.model,
    reply: reply,
    total_time: response?.usage?.total_time || 0,
  };

  let llamaSession = await Llama.findOne({
    user: userId,
    sessionId: currentSessionId,
  });

  if (llamaSession) {
    llamaSession.responses.push(responseData);
    await llamaSession.save();
  } else {
    llamaSession = await Llama.create({
      user: userId,
      sessionId: currentSessionId,
      responses: [responseData],
    });

    await UserModel.findByIdAndUpdate(userId, {
      $push: { llamaAiSessions: llamaSession._id },
    });
  }

  sendResponse(res, {
    statusCode: httpStatus.OK,
    success: true,
    message: 'Response processed successfully.',
    data: reply,
  });
});

