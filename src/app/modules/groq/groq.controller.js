import { ConversationChain } from 'langchain/chains';
import { BufferMemory } from 'langchain/memory';
import config from '../../../../config/index.js';

const groq = new Groq({ apiKey: config.groq_api_key });



// Initialize memory
const memory = new BufferMemory({
  returnMessages: true,
  memoryKey: 'history',
});

// Custom Groq API call function
const groqCall = async (prompt) => {
  try {
    const response = await groq?.chat?.completions?.create({
      messages: [{ role: 'user', content: prompt }],
      model: 'llama3-8b-8192',
    });
    return response?.choices[0]?.message?.content || 'No response generated';
  } catch (error) {
    console.error("Groq API Error:", error.message);
    throw new Error("Failed to fetch response from Groq");
  }
};

// Groq AI Get Response Handler
const GroqAiGetResponse = catchAsync(async (req, res) => {
  const prompt = req.body?.prompt;
  const userId = req.body?.user;
  const sessionId = req.body?.sessionId;

  const currentSessionId = sessionId || generateSessionId(24);

  if (!prompt) {
    return sendResponse(res, {
      statusCode: httpStatus.BAD_REQUEST,
      success: false,
      message: 'Validation Error',
      errorMessages: [{ path: 'prompt', message: 'Prompt is required.' }],
    });
  }

  const user = await UserModel.findById(userId);
  if (!user) {
    return sendResponse(res, {
      statusCode: httpStatus.NOT_FOUND,
      success: false,
      message: 'User not found.',
    });
  }

  // Define ConversationChain with the custom LLM call function for Groq
  const conversation = new ConversationChain({
    memory,
    llm: {
      async call({ input }) {
        const reply = await groqCall(input); // Call Groq API inside LangChain
        return { text: reply };
      },
    },
  });

  let response;
  try {
    // Call the conversation chain (note: using `call` here)
    response = await conversation.call({ input: prompt });
  } catch (error) {
    console.error('Groq SDK Error:', error.message);
    return sendResponse(res, {
      statusCode: httpStatus.INTERNAL_SERVER_ERROR,
      success: false,
      message: 'AI model processing failed.',
    });
  }

  const reply = response?.text || null;
  if (!reply) {
    console.error('Error: No valid reply generated by Groq SDK.');
    return sendResponse(res, {
      statusCode: httpStatus.BAD_REQUEST,
      success: false,
      message: 'Validation Error',
      errorMessages: [
        {
          path: 'message',
          message: 'Reply could not be generated by the AI model.',
        },
      ],
    });
  }

  let llamaSession = await Llama.findOne({
    user: userId,
    sessionId: currentSessionId,
  });

  if (llamaSession) {
    llamaSession.responses.push({ prompt, reply });
    await llamaSession.save();
  } else {
    llamaSession = await Llama.create({
      user: userId,
      sessionId: currentSessionId,
      responses: [{ prompt, reply }],
    });

    await UserModel.findByIdAndUpdate(userId, {
      $push: { llamaAiSessions: llamaSession._id },
    });
  }

  sendResponse(res, {
    statusCode: httpStatus.OK,
    success: true,
    message: 'Response processed successfully.',
    data: { sessionId: currentSessionId, reply },
  });
});













const GroqAiGetResponseAnonymously = catchAsync(async (req, res) => {
  const prompt = req.body?.prompt;

  if (!prompt) {
    return sendResponse(res, {
      statusCode: httpStatus.BAD_REQUEST,
      success: false,
      message: 'Validation Error',
      errorMessages: [{ path: 'prompt', message: 'Prompt is required.' }],
    });
  }

  let response;
  try {
    response = await groq?.chat?.completions?.create({
      messages: [{ role: 'user', content: prompt }],
      model: 'llama3-8b-8192',
    });
  } catch (error) {
    console.error('Groq SDK Error:', error.message);
    return sendResponse(res, {
      statusCode: httpStatus.INTERNAL_SERVER_ERROR,
      success: false,
      message: 'AI model processing failed.',
    });
  }

  const reply = response?.choices?.[0]?.message?.content || null;

  if (!reply) {
    console.error('Error: No valid reply generated by Groq SDK.');
    return sendResponse(res, {
      statusCode: httpStatus.BAD_REQUEST,
      success: false,
      message: 'Validation Error',
      errorMessages: [
        {
          path: 'message',
          message: 'Reply could not be generated by the AI model.',
        },
      ],
    });
  }

  const responseData = {
    prompt,
    model: response?.model,
    reply: reply,
    total_time: response?.usage?.total_time || 0,
  };

  sendResponse(res, {
    statusCode: httpStatus.OK,
    success: true,
    message: 'Response processed successfully.',
    data: responseData,
  });
});

